//! The generated pre-parse facts of `prelude.js` (`prelude_facts.rs`) must be the facts that a pre-parse of the current text gives. The file
//! also has `TOP`: the name and the fact id of each top-level function, which `Lazy::prelude_fn` reads.
//! After a change of `prelude.js`, of the parser, or of the fields of `FnFacts` or `Facts`, make the file again:
//!
//!     BLESS_PRELUDE_FACTS=1 cargo test -p bare-js2 --lib prelude_facts
//!
//! If `FnFacts` changed, the old file may not compile. Then cut it to `pub fn facts() -> Facts { Facts::default() }` (and the `use`
//! lines it needs), run the command, and the test writes the whole file.
use crate::facts::Facts;
use crate::parse::{Limits, parse_script_lazy};
use crate::script::PRELUDE;
use std::fmt::Write;

/// The source of `prelude_facts.rs` for the facts of `PRELUDE`.
fn render() -> String {
    let mut facts = Facts::new();
    parse_script_lazy(PRELUDE, Limits::default(), &mut facts).expect("the prelude parses");
    let mut s = String::new();
    s.push_str("//! GENERATED by the test `prelude_facts` (`prelude_facts_tests.rs`): the pre-parse facts of `prelude.js`. Do not edit.\n");
    s.push_str("//! `script::load` reads them instead of pre-parsing the prelude (docs/design-js2-prelude.md, option B').\n");
    s.push_str("//! The test fails when this file and the text of `prelude.js` do not agree.\n\n");
    s.push_str("use crate::ast::{FuncKind as K, FuncMode as M, Span as S};\nuse crate::facts::{FnFacts as F, Facts};\n\n");
    let sp = |s: Option<crate::ast::Span>| match s {
        Some(n) => format!("Some(S {{ start: {}, end: {} }})", n.start, n.end),
        None => "None".into(),
    };
    writeln!(s, "static FNS: [F; {}] = [", facts.fns.len()).unwrap();
    for f in &facts.fns {
        writeln!(
            s,
            "    F {{ start: {}, parse_at: {}, end: {}, name: {}, kind: K::{:?}, mode: M::{:?}, flags: {}, strict: {}, strict_out: {}, simple: {}, no_in: {}, ctx: {}, length: {}, sub: {}, caps: {}, ncaps: {} }},",
            f.start, f.parse_at, f.end, sp(f.name), f.kind, f.mode, f.flags, f.strict, f.strict_out, f.simple, f.no_in, f.ctx, f.length, f.sub, f.caps, f.ncaps
        )
        .unwrap();
    }
    s.push_str("];\n\n");
    writeln!(s, "static CAPS: [S; {}] = [", facts.caps.len()).unwrap();
    for c in &facts.caps {
        writeln!(s, "    S {{ start: {}, end: {} }},", c.start, c.end).unwrap();
    }
    s.push_str("];\n\n");
    let tops: Vec<_> = facts.children(None).map(|id| (PRELUDE[facts.get(id).name.expect("a top-level function has a name").start as usize..facts.get(id).name.unwrap().end as usize].to_string(), id)).collect();
    s.push_str("/// The top-level functions of `prelude.js`: the name and the id of its facts.\n");
    writeln!(s, "pub static TOP: [(&str, u32); {}] = [", tops.len()).unwrap();
    for (n, id) in tops.iter().rev() {
        writeln!(s, "    ({n:?}, {id}),").unwrap();
    }
    s.push_str("];\n\n");
    writeln!(s, "static BY_START: [u32; {}] = {:?};\n", facts.by_start.len(), facts.by_start).unwrap();
    s.push_str("/// The facts of `prelude.js`, as a lazy pre-parse of it gives them.\n");
    writeln!(
        s,
        "pub fn facts() -> Facts {{\n    Facts {{ fns: FNS.to_vec(), caps: CAPS.to_vec(), by_start: BY_START.to_vec(), preparsed: {}, module: {} }}\n}}",
        facts.preparsed, facts.module
    )
    .unwrap();
    s
}

#[test]
fn prelude_facts_file_is_up_to_date() {
    let want = render();
    if std::env::var_os("BLESS_PRELUDE_FACTS").is_some() {
        std::fs::write(concat!(env!("CARGO_MANIFEST_DIR"), "/src/prelude_facts.rs"), &want).expect("write prelude_facts.rs");
        return;
    }
    assert!(
        include_str!("prelude_facts.rs") == want,
        "crates/js2/src/prelude_facts.rs is out of date with prelude.js: run `BLESS_PRELUDE_FACTS=1 cargo test -p bare-js2 --lib prelude_facts` and commit the file"
    );
}

/// Each name in `prelude_pre.rs` and in a lazy table that asks for a top-level function must be one.
#[test]
fn every_prelude_slot_function_exists() {
    for (name, pd) in crate::prelude_pre::PRE {
        if let crate::prelude_pre::Pd::Func(top) = pd {
            assert_eq!(name, top);
            assert!(crate::prelude_facts::TOP.iter().any(|(n, _)| n == top), "prelude.js has no function {top}");
        }
    }
}

#[test]
fn prelude_facts_equal_a_fresh_pre_parse() {
    let mut fresh = Facts::new();
    parse_script_lazy(PRELUDE, Limits::default(), &mut fresh).unwrap();
    let k = crate::prelude_facts::facts();
    assert_eq!(format!("{:?}", fresh), format!("{:?}", k));
}
