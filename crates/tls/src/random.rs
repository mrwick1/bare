//! Secure random bytes from the operating system, and nothing else.
//!
//! There is no fallback. No clock, process id or home-made generator is ever used. If the
//! OS source fails, the caller gets an error and must stop. A weak secret is worse than no secret.
//!
//! Source: `/dev/urandom` on Unix (Linux, macOS, BSD). The kernel generator behind it is
//! seeded and never runs dry. On Linux 5.18 and later it is ready before user space
//! starts; on older kernels very early boot could still be a risk. `Read::read_exact`
//! retries short reads and `Interrupted` (EINTR) by itself, and turns end-of-file into an
//! error. Other platforms return `Unsupported` until someone adds a source for them.
//! Generated bytes are never printed or logged here, and `RandomError` carries none.

use std::fmt;
use std::io::{self, ErrorKind, Read};

#[derive(Debug)]
pub enum RandomError {
    /// This platform has no OS random source wired in yet.
    Unsupported,
    /// Opening or reading the source failed. The error kind says why; there are no secret bytes in it.
    Io(ErrorKind),
}

impl fmt::Display for RandomError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            RandomError::Unsupported => write!(f, "no OS random source on this platform"),
            RandomError::Io(k) => write!(f, "OS random source failed: {k}"),
        }
    }
}
impl std::error::Error for RandomError {}

/// Fill `buf` from `src`, all of it or an error. On error `buf` may be partly written,
/// so the caller must not use it. Split out from `fill` so tests can use a fake source.
fn fill_from<R: Read>(src: &mut R, buf: &mut [u8]) -> Result<(), RandomError> {
    src.read_exact(buf).map_err(|e| RandomError::Io(e.kind()))
}

/// Fill `buf` with random bytes from the OS. Fails closed: on any error, `buf` is zeroed
/// again so a caller that ignores the error does not keep half-random data.
#[cfg(unix)]
pub fn fill(buf: &mut [u8]) -> Result<(), RandomError> {
    let r = std::fs::File::open("/dev/urandom")
        .map_err(|e: io::Error| RandomError::Io(e.kind()))
        .and_then(|mut f| fill_from(&mut f, buf));
    if r.is_err() {
        buf.fill(0);
    }
    r
}

#[cfg(not(unix))]
pub fn fill(_buf: &mut [u8]) -> Result<(), RandomError> {
    Err(RandomError::Unsupported)
}

/// 32 random bytes, the size of an X25519 secret scalar or a TLS 1.3 random.
pub fn random_32() -> Result<[u8; 32], RandomError> {
    let mut b = [0u8; 32];
    fill(&mut b)?;
    Ok(b)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A fake source: gives 1 byte per call, sometimes `Interrupted`, then fails or ends.
    struct Fake {
        calls: usize,
        left: usize,
        end: Option<ErrorKind>,
    }
    impl Read for Fake {
        fn read(&mut self, out: &mut [u8]) -> io::Result<usize> {
            self.calls += 1;
            if self.calls % 3 == 0 {
                return Err(ErrorKind::Interrupted.into());
            }
            if self.left == 0 {
                return match self.end {
                    Some(k) => Err(k.into()),
                    None => Ok(0), // end-of-file
                };
            }
            self.left -= 1;
            out[0] = 0xAB;
            Ok(1)
        }
    }

    #[test]
    fn short_reads_and_eintr_are_retried() {
        let mut buf = [0u8; 40];
        let mut f = Fake { calls: 0, left: 40, end: None };
        fill_from(&mut f, &mut buf).unwrap();
        assert_eq!(buf, [0xAB; 40]);
        assert!(f.calls > 40, "the interrupted calls were retried");
    }

    #[test]
    fn eof_before_full_is_an_error() {
        let mut f = Fake { calls: 0, left: 10, end: None };
        match fill_from(&mut f, &mut [0u8; 32]) {
            Err(RandomError::Io(ErrorKind::UnexpectedEof)) => {}
            other => panic!("{other:?}"),
        }
    }

    #[test]
    fn hard_error_is_passed_on() {
        let mut f = Fake { calls: 0, left: 5, end: Some(ErrorKind::PermissionDenied) };
        match fill_from(&mut f, &mut [0u8; 32]) {
            Err(RandomError::Io(ErrorKind::PermissionDenied)) => {}
            other => panic!("{other:?}"),
        }
    }

    #[test]
    fn error_message_has_no_bytes() {
        let e = RandomError::Io(ErrorKind::PermissionDenied);
        assert_eq!(e.to_string(), "OS random source failed: permission denied");
        assert!(RandomError::Unsupported.to_string().contains("no OS random source"));
    }

    #[cfg(unix)]
    #[test]
    fn os_source_fills_and_differs() {
        let (a, b) = (random_32().unwrap(), random_32().unwrap());
        assert_ne!(a, b); // chance of a false failure: 2^-256
        assert_ne!(a, [0; 32]);
        let mut big = vec![0u8; 100_000]; // more than one pipe/page read
        fill(&mut big).unwrap();
        assert!(big.iter().any(|&x| x != 0));
        fill(&mut []).unwrap(); // an empty request is fine
    }

    #[cfg(unix)]
    #[test]
    fn rough_bit_balance() {
        // Not a proof of quality: a catch for a stuck or all-zero source.
        let mut big = vec![0u8; 1 << 20];
        fill(&mut big).unwrap();
        let ones: u64 = big.iter().map(|b| b.count_ones() as u64).sum();
        let total = (big.len() * 8) as u64;
        assert!(ones.abs_diff(total / 2) < total / 100, "ones = {ones} of {total}");
    }
}
