#!/usr/bin/env python3 -I
"""Generate TLS 1.2 test vectors for crates/tls/src/tls12.rs and record.rs (needs the Python `cryptography` package).

Run: cd tools/fixtures/tls12 && python3 -I gen.py
Writes vectors.txt. The signing keys are made in memory and are never written.

Format (all hex):
  prf SECRET LABEL_HEX SEED_HEX OUT_HEX        P_SHA256 output (the PRF of RFC 5246 section 5); OUT is 100 bytes
  ske NAME SCHEME KEYKIND KEY SIG              signature over client_random(0x11*32) || server_random(0x22*32) ||
                                               03 00 1d 20 || point(0x33*32). KEYKIND p256, p384 (uncompressed point) or
                                               rsa (RSAPublicKey DER). SCHEME is the TLS SignatureScheme.
  skp NAME SCHEME KEYKIND KEY SIG              the same with a P-256 ephemeral point: 03 00 17 41 || 04 || 0x33*64
  kdf PMS CR SR SESSION_HASH EMS PLAIN KEYBLOCK FIN
                                               extended master secret, plain master secret, 40-byte key block (from the
                                               extended one), client "verify_data" over a 0x66*32 hash
  rec KEY SALT SEQ TYPE PLAINTEXT RECORD       one protected AES-128-GCM record (RFC 5288)
The PRF is the Python code below. It is checked against the public test vector of the IETF TLS mailing list
(secret 9bbe436b..., label "test label", first line of the `prf` vector).
"""
import hashlib, hmac, os
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import ec, padding, rsa
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat

HERE = os.path.dirname(os.path.abspath(__file__))
h = lambda b: b.hex()


def prf(secret, label, seed, n):
    s = label + seed
    a, out = s, b""
    while len(out) < n:
        a = hmac.new(secret, a, hashlib.sha256).digest()
        out += hmac.new(secret, a + s, hashlib.sha256).digest()
    return out[:n]


lines = ["# TLS 1.2 vectors for crates/tls. Generated by gen.py. Do not edit."]

sec = bytes.fromhex("9bbe436ba940f017b17652849a71db35")
seed = bytes.fromhex("a0ba9f936cda311827a6f796ffd5198c")
out = prf(sec, b"test label", seed, 100)
assert out.hex().startswith("e3f229ba727be17b8d122620557cd453c2aab21d07c3d495329b52d4e61edb5a")
lines.append(f"prf {h(sec)} {h(b'test label')} {h(seed)} {h(out)}")

# ServerKeyExchange signatures.
cr, sr, point = b"\x11" * 32, b"\x22" * 32, b"\x33" * 32
signed = cr + sr + bytes([3, 0, 0x1D, 32]) + point
signed_p256 = cr + sr + bytes([3, 0, 0x17, 65]) + b"\x04" + b"\x33" * 64
sha = {256: hashes.SHA256(), 384: hashes.SHA384()}
keys = {"p256": ec.generate_private_key(ec.SECP256R1()), "p384": ec.generate_private_key(ec.SECP384R1())}
rkey = rsa.generate_private_key(65537, 2048)
for name, k in keys.items():
    pub = k.public_key().public_bytes(Encoding.X962, PublicFormat.UncompressedPoint)
    for scheme, bits in ((0x0403, 256), (0x0503, 384)):
        lines.append(f"ske {name}-{bits} {scheme:04x} {name} {h(pub)} {h(k.sign(signed, ec.ECDSA(sha[bits])))}")
        lines.append(f"skp {name}-{bits} {scheme:04x} {name} {h(pub)} {h(k.sign(signed_p256, ec.ECDSA(sha[bits])))}")
rpub = rkey.public_key().public_bytes(Encoding.DER, PublicFormat.PKCS1)
for scheme, bits, pss in ((0x0804, 256, 1), (0x0805, 384, 1), (0x0401, 256, 0), (0x0501, 384, 0)):
    pad = padding.PSS(padding.MGF1(sha[bits]), bits // 8) if pss else padding.PKCS1v15()
    kind = "pss" if pss else "pkcs1"
    lines.append(f"ske rsa-{kind}-{bits} {scheme:04x} rsa {h(rpub)} {h(rkey.sign(signed, pad, sha[bits]))}")
    lines.append(f"skp rsa-{kind}-{bits} {scheme:04x} rsa {h(rpub)} {h(rkey.sign(signed_p256, pad, sha[bits]))}")

# Key derivation.
pms, cr, sr, sh = b"\x44" * 32, b"\x11" * 32, b"\x22" * 32, b"\x55" * 32
ems = prf(pms, b"extended master secret", sh, 48)
plain = prf(pms, b"master secret", cr + sr, 48)
kb = prf(ems, b"key expansion", sr + cr, 40)
fin = prf(ems, b"client finished", b"\x66" * 32, 12)
lines.append(f"kdf {h(pms)} {h(cr)} {h(sr)} {h(sh)} {h(ems)} {h(plain)} {h(kb)} {h(fin)}")

# Records.
key, salt = bytes(range(16)), bytes([0xA0, 0xA1, 0xA2, 0xA3])
for seq, ty, plain in ((0, 22, bytes.fromhex("1400000c") + bytes(range(12))), (5, 23, b"hello, tls 1.2")):
    explicit = seq.to_bytes(8, "big")
    aad = explicit + bytes([ty, 3, 3]) + len(plain).to_bytes(2, "big")
    ct = AESGCM(key).encrypt(salt + explicit, plain, aad)
    body = explicit + ct
    rec = bytes([ty, 3, 3]) + len(body).to_bytes(2, "big") + body
    lines.append(f"rec {h(key)} {h(salt)} {seq} {ty} {h(plain)} {h(rec)}")

open(os.path.join(HERE, "vectors.txt"), "w").write("\n".join(lines) + "\n")
