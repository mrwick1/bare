// Generate crates/js/src/intl_rtf_data.rs (included by intl.rs): English relative time patterns from Node's ICU (CLDR data, Unicode license).
// Only Intl.RelativeTimeFormat of this Node runs here; no page code.
//   node tools/js/intl_rtf_gen.mjs > crates/js/src/intl_rtf_data.rs
//
// A pattern is "in {n}{label}" (future) or "{n}{label} ago" (past). `label` has its own space ("" or " days"), and one form for
// "1" and one for the rest. `auto` has the words for -1, 0 and 1 with numeric "auto" ("" for none). The script checks every
// pattern against Node for 6 numbers and both signs, and stops when one does not fit.
const VARIANTS = ["en-US", "en-CA", "en-GB"]; // en and en-US; en-CA; en-GB and en-IN (checked below)
const SAME = { "en-US": ["en"], "en-CA": [], "en-GB": ["en-IN"] };
const STYLES = ["long", "short", "narrow"];
const UNITS = ["second", "minute", "hour", "day", "week", "month", "quarter", "year"];
const label = (s, pre, post) => (pre ? s.slice(pre.length) : s).replace(/^(in )?\d+/, "").replace(/ ago$/, "");
let out = `// Generated by tools/js/intl_rtf_gen.mjs from Node ${process.version} (ICU ${process.versions.icu}, CLDR ${process.versions.cldr}). Do not edit.
// English relative time patterns (CLDR data, Unicode license: data/unicode/LICENSE.txt). The format is in the generator.

/// One unit of one style: the label after the number for 1 and for the other numbers (it holds its space), and the words for
/// -1, 0 and 1 with \`numeric: "auto"\` ("" for none).
pub struct RtfUnit {
    pub one: &'static str,
    pub other: &'static str,
    pub auto: [&'static str; 3],
}

/// Pattern variant of locale \`i\` of \`intl::LOCALES\` (en-US, en, en-CA, en-IN, en-GB): 0 US, 1 CA, 2 GB.
pub const RTF_VARIANT: [u8; 5] = [0, 0, 1, 2, 2];
/// Units by variant, style (long, short, narrow) and unit (second to year).
pub const RTF_DATA: [[[RtfUnit; 8]; 3]; 3] = [
`;
const q = (s) => JSON.stringify(s);
for (const v of VARIANTS) {
  out += "    [\n";
  for (const style of STYLES) {
    const always = new Intl.RelativeTimeFormat(v, { style, numeric: "always" });
    const auto = new Intl.RelativeTimeFormat(v, { style, numeric: "auto" });
    out += "        [\n";
    for (const u of UNITS) {
      const one = label(always.format(1, u)), other = label(always.format(2, u));
      for (const n of [-2, -1, 0, 1, 2, 5, -0, 1.5, 21]) {
        const l = Math.abs(n) === 1 ? one : other;
        const want = (n < 0 || Object.is(n, -0)) ? `${new Intl.NumberFormat(v).format(Math.abs(n))}${l} ago` : `in ${new Intl.NumberFormat(v).format(n)}${l}`;
        if (always.format(n, u) !== want) throw new Error(`${v} ${style} ${u} ${n}: ${always.format(n, u)} != ${want}`);
      }
      const a = [-1, 0, 1].map((n) => (auto.format(n, u) === always.format(n, u) ? "" : auto.format(n, u)));
      out += `            RtfUnit { one: ${q(one)}, other: ${q(other)}, auto: [${a.map(q).join(", ")}] },\n`;
    }
    out += "        ],\n";
  }
  out += "    ],\n";
}
out += "];\n";
for (const [v, others] of Object.entries(SAME)) for (const o of others) for (const style of STYLES) for (const numeric of ["always", "auto"]) for (const u of UNITS) for (const n of [-2, -1, 0, 1, 2, 5]) {
  const a = new Intl.RelativeTimeFormat(v, { style, numeric }).format(n, u), b = new Intl.RelativeTimeFormat(o, { style, numeric }).format(n, u);
  if (a !== b) throw new Error(`${o} differs from ${v}: ${style} ${numeric} ${u} ${n}: ${b} != ${a}`);
}
process.stdout.write(out);
