// A short list of common codes, not all of CLDR: an unknown code gives the code itself (fallback "code"). A row is
// (code, long, short, narrow); short and narrow are "" when they equal the long name. The names are those of en-US for every
// locale; the header lists the codes that en, en-CA, en-GB or en-IN names in another way.
const LANGS = "af am ar az be bg bn bs ca cs cy da de el en eo es et eu fa fi fil fr ga gl gu ha he hi hr hu hy id ig is it ja ka kk km kn ko la lo lt lv mi mk ml mn mr ms mt my nb ne nl no pa pl ps pt ro ru si sk sl so sq sr sv sw ta te th tl tr uk ur uz vi xh yo zh zu".split(" ");
// language-script and language-region tags that have a dialect name ("American English"); checked below
const DIALECTS = "ar-001 de-AT de-CH en-AU en-CA en-GB en-US es-419 es-ES es-MX fr-CA fr-CH nl-BE pt-BR pt-PT zh-Hans zh-Hant".split(" ");
const REGIONS = "001 002 019 142 150 419 AE AF AR AT AU BD BE BG BR BY CA CH CL CN CO CZ DE DK DZ EG ES ET EU FI FR GB GH GR HK HR HU ID IE IL IN IQ IR IS IT JP KE KR KZ LK LT LU LV MA MX MY NG NL NO NP NZ PE PH PK PL PT QA RO RS RU SA SE SG SI SK TH TR TW TZ UA UG US UY UZ VE VN ZA ZZ".split(" ");
const SCRIPTS = "Arab Armn Beng Cyrl Deva Ethi Geor Grek Gujr Guru Hang Hani Hans Hant Hebr Hira Jpan Kana Khmr Knda Kore Latn Mlym Taml Telu Thai Zzzz".split(" ");
const CURRENCIES = "AED ARS AUD BDT BRL CAD CHF CLP CNY COP CZK DKK EGP EUR GBP HKD HUF IDR ILS INR JPY KES KRW MXN MYR NGN NOK NZD PHP PKR PLN RUB SAR SEK SGD THB TRY TWD UAH USD VND ZAR".split(" ");
const CALENDARS = "buddhist chinese coptic dangi ethioaa ethiopic gregory hebrew indian islamic islamic-civil islamic-rgsa islamic-tbla islamic-umalqura iso8601 japanese persian roc".split(" ");
const FIELDS = "era year quarter month weekOfYear weekday day dayPeriod hour minute second timeZoneName".split(" ");
const STYLES = ["long", "short", "narrow"];
const OTHERS = ["en", "en-CA", "en-GB", "en-IN"];

const name = (loc, type, style, code, extra = {}) => new Intl.DisplayNames(loc, { type, style, fallback: "none", ...extra }).of(code);
const differ = new Set();
const esc = (s) => JSON.stringify(s);
function rows(type, codes, extra = {}) {
  const out = [];
  for (const c of [...codes].sort()) {
    const [l, s, n] = STYLES.map((st) => name("en-US", type, st, c, extra));
    if (l === undefined) throw new Error(`no name: ${type} ${c}`);
    for (const loc of OTHERS) for (const st of STYLES) {
      if (name(loc, type, st, c, extra) !== name("en-US", type, st, c, extra)) differ.add(`${type} ${c}`);
    }
    out.push(`    (${esc(c)}, ${esc(l)}, ${esc(s === l ? "" : s)}, ${esc(n === l ? "" : n)}),`);
  }
  return out.join("\n");
}
for (const d of DIALECTS) {
  if (name("en-US", "language", "long", d) === name("en-US", "language", "long", d, { languageDisplay: "standard" })) throw new Error(`no dialect name: ${d}`);
}
const table = (n, type, codes, extra) => `pub const ${n}: [(&str, &str, &str, &str); ${codes.length}] = [\n${rows(type, codes, extra)}\n];\n`;
const body = `${table("NAMES_LANGUAGE", "language", LANGS, { languageDisplay: "standard" })}${table("NAMES_DIALECT", "language", DIALECTS)}${table("NAMES_REGION", "region", REGIONS)}${table("NAMES_SCRIPT", "script", SCRIPTS)}${table("NAMES_CURRENCY", "currency", CURRENCIES)}${table("NAMES_CALENDAR", "calendar", CALENDARS)}${table("NAMES_FIELD", "dateTimeField", FIELDS)}`;
console.log(`// Generated by tools/js/intl_names_gen.mjs from Node ${process.version} (ICU ${process.versions.icu}, CLDR ${process.versions.cldr}). Do not edit.
// English display names (CLDR data, Unicode license: data/unicode/LICENSE.txt). A row is (code, long, short, narrow); short and
// narrow are "" when they equal the long name. Rows are sorted by code (binary search). The names are those of en-US; en, en-CA,
// en-GB or en-IN has another name for: ${[...differ].join(", ")}.

${body}`.trimEnd());
