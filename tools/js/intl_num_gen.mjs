// Generate crates/js/src/intl_num_data.rs: currency symbols and digits for Intl.NumberFormat, from Node's ICU (CLDR data, Unicode
// license). Only Intl.NumberFormat of this Node runs here; no page code.
//   node tools/js/intl_num_gen.mjs > crates/js/src/intl_num_data.rs
//
// A currency that has no entry shows its code and has 2 digits. `space` is true when the locale puts a no-break space
// between the symbol and the digits (the symbol does not end in a Unicode symbol character).
const LOCALES = ["en-US", "en", "en-CA", "en-IN", "en-GB"];
const cur = [...Intl.supportedValuesOf("currency"), "XXX"].sort();
const part = (loc, c, d, n = 1) => new Intl.NumberFormat(loc, { style: "currency", currency: c, currencyDisplay: d }).formatToParts(n);
const sym = (loc, c, d) => part(loc, c, d).find((p) => p.type === "currency").value;
const space = (loc, c, d) => part(loc, c, d).some((p) => p.type === "literal" && p.value === " ");
const q = (s) => JSON.stringify(s).replace(/[^\x20-\x7e]/g, (ch) => `\\u{${ch.codePointAt(0).toString(16)}}`);
const row = (c, s, sp) => `(${q(c)}, ${q(s)}, ${sp})`;

const base = [], over = [], narrow = [], digits = [];
for (const c of cur) {
  const s = sym("en-US", c, "symbol");
  if (s !== c) base.push(row(c, s, space("en-US", c, "symbol")));
  const n = sym("en-US", c, "narrowSymbol");
  if (n !== s) narrow.push(row(c, n, space("en-US", c, "narrowSymbol")));
  const d = new Intl.NumberFormat("en", { style: "currency", currency: c }).resolvedOptions().maximumFractionDigits;
  if (d !== 2) digits.push(`(${q(c)}, ${d})`);
  for (const [i, l] of LOCALES.entries()) {
    if (sym(l, c, "symbol") !== s) over.push(`(${i}, ${q(c)}, ${q(sym(l, c, "symbol"))}, ${space(l, c, "symbol")})`);
    if (sym(l, c, "narrowSymbol") !== n) throw new Error(`narrow symbol of ${c} differs in ${l}`);
  }
}
const arr = (name, type, rows, doc) => `${doc}\npub const ${name}: [${type}; ${rows.length}] = [\n${rows.map((r) => "    " + r + ",").join("\n")}\n];\n`;
process.stdout.write(`// Generated by tools/js/intl_num_gen.mjs from Node ${process.version} (ICU ${process.versions.icu}, CLDR ${process.versions.cldr}). Do not edit.
// Currency data of the English locales (CLDR data, Unicode license: data/unicode/LICENSE.txt). Tables are sorted by code.

${arr("SYMBOLS", "(&str, &str, bool)", base, "/// (code, symbol, space) of `currencyDisplay: \"symbol\"` in en-US and en. A code that is not here shows itself.")}
${arr("SYMBOLS_LOCALE", "(u8, &str, &str, bool)", over, "/// (locale, code, symbol, space) where a locale differs from en-US. The locale is an index of `intl_data::LOCALES`.")}
${arr("NARROW", "(&str, &str, bool)", narrow, "/// (code, symbol, space) of `currencyDisplay: \"narrowSymbol\"` when it differs from the symbol (the same in all locales).")}
${arr("DIGITS", "(&str, u8)", digits, "/// (code, digits) of the currencies that do not have 2 digits.")}`);
