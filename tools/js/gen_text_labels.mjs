// Generates crates/js/src/text_labels.rs: the WHATWG Encoding label table, read from Node's own copy.
// It only reads Node's built-in source text. It runs no fetched code.
//   node --expose-internals tools/js/gen_text_labels.mjs > crates/js/src/text_labels.rs
const src = process.binding("natives")["internal/encoding"];
const start = src.indexOf("const encodings = new SafeMap([");
const body = src.slice(start, src.indexOf("]);", start));
const pairs = [...body.matchAll(/\['([^']+)', '([^']+)'\]/g)].map((m) => [m[1], m[2]]);
pairs.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
console.log("// Generated by tools/js/gen_text_labels.mjs. Do not edit.");
console.log("// Each pair is (lowercase label, encoding name), sorted by label, from the WHATWG Encoding Standard.");
console.log("pub static LABELS: &[(&str, &str)] = &[");
for (const [l, n] of pairs) console.log(`    (${JSON.stringify(l)}, ${JSON.stringify(n)}),`);
console.log("];");
