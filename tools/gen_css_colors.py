#!/usr/bin/env python3
"""Generate crates/css/src/colors.rs from data/css/color-name.js.

Run from the repo root: python3 tools/gen_css_colors.py

Source (MIT license in data/css/LICENSE.txt):
  https://github.com/colorjs/color-name
It lists the 148 named colors of CSS Color Level 4.

To update: download the new file over the old one, then run this script.
"""
import re

with open("data/css/color-name.js", encoding="utf-8") as f:
    text = f.read()

colors = sorted((m[0], int(m[1]), int(m[2]), int(m[3])) for m in re.findall(r"(\w+): \[(\d+), (\d+), (\d+)\]", text))
assert len(colors) == 148, len(colors)

with open("crates/css/src/colors.rs", "w", encoding="utf-8") as out:
    out.write("// Generated by tools/gen_css_colors.py from data/css/color-name.js. Do not edit.\n")
    out.write("// Source: https://github.com/colorjs/color-name (MIT, see data/css/LICENSE.txt).\n\n")
    out.write("/// The named colors of CSS: (name in lowercase, red, green, blue). Sorted by name, for a binary search.\n")
    out.write("/// `transparent` is not here: it has an alpha of 0, and `Color::named` adds it.\n")
    out.write("pub static NAMED_COLORS: &[(&str, u8, u8, u8)] = &[\n")
    for name, r, g, b in colors:
        out.write(f'    ("{name}", {r}, {g}, {b}),\n')
    out.write("];\n")
